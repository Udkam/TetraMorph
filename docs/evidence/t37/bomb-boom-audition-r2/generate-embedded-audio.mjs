import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const entries = [
  ['deep', 'audio/ogg', 'sources/assets/kodack-deep-explosion-hq-preview.ogg'],
  ['muffled', 'audio/wav', 'sources/assets/nenadsimic-muffled-distant-explosion.wav'],
];

const embedded = {};
for (const [id, mime, relativePath] of entries) {
  const bytes = await readFile(join(root, relativePath));
  embedded[id] = {
    mime,
    relativePath,
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    dataUri: `data:${mime};base64,${bytes.toString('base64')}`,
  };
}

const output = [
  '// Generated by generate-embedded-audio.mjs. Do not hand-edit.',
  `window.BOMB_R2_EMBEDDED = Object.freeze(${JSON.stringify(embedded)});`,
  '',
].join('\n');
await writeFile(join(root, 'embedded-audio.js'), output, 'utf8');
